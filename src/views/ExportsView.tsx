import { useState } from "react";
import { AlertTriangle, ArrowRight, CheckCircle2, Download, FileSpreadsheet, ListChecks, Table2 } from "lucide-react";
import type { ExportKind, Period, Profile } from "../api";
import { api } from "../api";
import { Badge, Button, Card, CardHeader, InlineAlert, PageHeader, cn } from "../components/ui";
import type { NoticeKind } from "../components/Toast";
import { messages as m } from "../constants/messages";
import { formatRangeLabel, periodKindLabel } from "../domain/date";
import { pluralize } from "../domain/format";
import type { MissingSummary } from "../domain/period";
import type { DateEntry } from "../domain/period";

type ExportsViewProps = {
  period: Period;
  profile: Profile;
  records: Period["dailyRecords"];
  missingSummary: MissingSummary;
  nextMissing: DateEntry | null;
  onSelect: (date: string) => void;
  onGoTo: (path: string) => void;
  notify: (kind: NoticeKind, message: string) => void;
};

const buttonLabel = (kind: ExportKind) => kind === "dtr" ? "Download DTR" : "Download accomplishments";

export const ExportsView = ({ period, profile, records, missingSummary, nextMissing, onSelect, onGoTo, notify }: ExportsViewProps) => {
  const [loadingKind, setLoadingKind] = useState<ExportKind | null>(null);
  const [error, setError] = useState("");
  const attention = missingSummary.missing + missingSummary.today;
  const missingName = !profile.employeeName.trim();

  const download = async (kind: ExportKind) => {
    setLoadingKind(kind);
    setError("");
    try {
      const { blob, filename } = await api.exportWorkbook(period.id, kind);
      const url = URL.createObjectURL(blob);
      const anchor = document.createElement("a");
      anchor.href = url;
      anchor.download = filename;
      document.body.appendChild(anchor);
      anchor.click();
      anchor.remove();
      window.setTimeout(() => URL.revokeObjectURL(url), 1500);
      notify("success", `${kind === "dtr" ? "DTR" : "Accomplishments"} workbook download started.`);
    } catch (reason) {
      const message = reason instanceof Error ? reason.message : m.saveError;
      setError(message);
      notify("error", message);
    } finally {
      setLoadingKind(null);
    }
  };

  const cards: Array<{ kind: ExportKind; title: string; description: string; icon: typeof FileSpreadsheet; detail: string }> = [
    {
      kind: "dtr",
      title: "DTR workbook",
      description: "Daily attendance, leave, overtime, and calculated hour detail for the selected reporting period.",
      icon: FileSpreadsheet,
      detail: `${records.length} saved ${records.length === 1 ? "date" : "dates"} · Company DTR template`
    },
    {
      kind: "accomplishments",
      title: "Accomplishments workbook",
      description: "Task lines, activity, accomplishment type and status, hours spent, and remarks for the selected period.",
      icon: Table2,
      detail: `${records.filter((record) => record.tasks.length > 0).length} dates with tasks · Company accomplishments template`
    }
  ];

  return (
    <div className="space-y-5">
      <PageHeader
        eyebrow={m.exports}
        title="Download the cutoff workbooks"
        description={`${formatRangeLabel(period.startDate, period.endDate)} · ${periodKindLabel(period.startDate, period.endDate)}. Workbooks are generated by the backend using the company templates.`}
        actions={<Button variant="secondary" icon={<ListChecks className="size-4" aria-hidden="true" />} onClick={() => onGoTo("/review")}>Review period</Button>}
      />

      {missingName && (
        <InlineAlert tone="warning" title="Employee name is missing" action={<Button size="sm" variant="secondary" onClick={() => onGoTo("/settings")}>Open settings <ArrowRight className="size-3.5" aria-hidden="true" /></Button>}>
          {m.missingName} Add the employee name before creating a final workbook.
        </InlineAlert>
      )}

      {attention > 0 ? (
        <InlineAlert
          tone="warning"
          title={attention === 1 ? "1 date has no saved entry" : `${attention} dates have no saved entry`}
          action={<Button size="sm" variant="secondary" onClick={() => nextMissing && onSelect(nextMissing.date)}>Open next missing <ArrowRight className="size-3.5" aria-hidden="true" /></Button>}
        >
          {missingSummary.missing > 0 && `${missingSummary.missing} past ${missingSummary.missing === 1 ? "date is" : "dates are"} missing`}
          {missingSummary.missing > 0 && missingSummary.today > 0 && " and "}
          {missingSummary.today > 0 && "today is not saved"}
          . Exports will include only the saved records.
          {missingSummary.upcoming > 0 ? ` ${pluralize(missingSummary.upcoming, "upcoming date")} can still be recorded early.` : ""}
        </InlineAlert>
      ) : missingSummary.upcoming > 0 ? (
        <InlineAlert tone="info" title={`${pluralize(missingSummary.upcoming, "upcoming date")} have no entry yet`}>
          All dates through today are saved. Upcoming dates can be recorded before the cutoff ends.
        </InlineAlert>
      ) : (
        <InlineAlert tone="success" title="The period is complete">
          Every date in this reporting period has a saved entry.
        </InlineAlert>
      )}

      {error && <InlineAlert tone="danger" title="The workbook could not be downloaded" onDismiss={() => setError("")}>{error}</InlineAlert>}

      <div className="grid gap-4 lg:grid-cols-2">
        {cards.map((card) => {
          const Icon = card.icon;
          const loading = loadingKind === card.kind;
          return (
            <Card key={card.kind} className={cn("flex flex-col", card.kind === "dtr" && "border-brand/15")}>
              <div className="flex items-start justify-between gap-4">
                <span className={cn("grid size-12 place-items-center rounded-xl", card.kind === "dtr" ? "bg-brand-soft text-brand" : "bg-success-soft text-success")} aria-hidden="true">
                  <Icon className="size-6" />
                </span>
                <Badge tone="neutral"><span className="font-mono text-[10px]">.xlsx</span></Badge>
              </div>
              <h2 className="mt-4 text-lg font-semibold tracking-[-.02em] text-ink">{card.title}</h2>
              <p className="mt-2 text-[13px] leading-relaxed text-muted">{card.description}</p>
              <div className="mt-4 rounded-lg bg-canvas px-3 py-2.5 text-[11px] leading-relaxed text-muted">
                <p className="flex items-center gap-1.5"><CheckCircle2 className="size-3.5 text-success" aria-hidden="true" /> {card.detail}</p>
                <p className="mt-1 flex items-center gap-1.5"><FileSpreadsheet className="size-3.5 text-muted" aria-hidden="true" /> {formatRangeLabel(period.startDate, period.endDate)}</p>
              </div>
              <div className="mt-auto pt-5">
                <Button className="w-full" loading={loading} onClick={() => void download(card.kind)} icon={<Download className="size-4" aria-hidden="true" />}>
                  {loading ? "Preparing workbook..." : buttonLabel(card.kind)}
                </Button>
                <p className="mt-2 text-center text-[11px] text-muted">The browser download begins as soon as the backend finishes the workbook.</p>
              </div>
            </Card>
          );
        })}
      </div>

      <Card>
        <CardHeader title="What is included" description="The backend owns workbook layout, formatting, and file naming." />
        <div className="grid gap-4 sm:grid-cols-3">
          <div className="rounded-xl border border-line bg-canvas/60 p-4">
            <p className="text-[12px] font-semibold text-ink">Attendance detail</p>
            <p className="mt-1 text-[12px] leading-relaxed text-muted">Saved dates, day types, times, breaks, and every calculated category.</p>
          </div>
          <div className="rounded-xl border border-line bg-canvas/60 p-4">
            <p className="text-[12px] font-semibold text-ink">Leave and signoff</p>
            <p className="mt-1 text-[12px] leading-relaxed text-muted">The period leave request, employee details, validator, and supervisor from the shared profile.</p>
          </div>
          <div className="rounded-xl border border-line bg-canvas/60 p-4">
            <p className="text-[12px] font-semibold text-ink">Accomplishments</p>
            <p className="mt-1 text-[12px] leading-relaxed text-muted">Activity, type, status, hours spent, task lines, and remarks for recorded dates.</p>
          </div>
        </div>
        <p className="mt-4 flex items-start gap-1.5 text-[11px] leading-relaxed text-muted">
          <AlertTriangle className="mt-0.5 size-3.5 shrink-0" aria-hidden="true" />
          The UI does not display percentage progress during a download because the browser handles the response. “Preparing workbook...” is shown only while the request is in flight.
        </p>
      </Card>
    </div>
  );
};
